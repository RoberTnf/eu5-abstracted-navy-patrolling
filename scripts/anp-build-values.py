#!/usr/bin/env python3
"""Build the Abstracted Navy Patrolling per-ship maritime presence lookup from vanilla:
    mod/in_game/common/script_values/anp_ship_values.txt

Run after every EU5 update:
    python3 scripts/anp-build-values.py

Script has no getter for a sub-unit's maritime presence, so this scans every unit_types file
(base game + DLC), resolves copy_from chains, and writes `anp_ship_maritime_presence`
(sub-unit scope): the vanilla `maritime_presence` of the sub-unit's type, as an if/else_if chain
on sub_unit_type with one branch per distinct value (largest groups first, so most ships match
early). Navy types without a value of their own or inherited get 0. Ship types this script never
saw (added by other mods) fall through to DEFAULT_PRESENCE.

A type with copy_from adds its own maritime_presence to the inherited one (vanilla uniques use
deltas like `maritime_presence = -0.06` next to `hull_size = -1`), so a type's presence is the
sum along its copy_from chain.
"""
import glob
import os
import re
from collections import defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.environ.get('EU5_GAME_DIR') or os.path.expanduser(
    '~/.local/share/Steam/steamapps/common/Europa Universalis V/game')
OUT = os.path.join(REPO, 'mod/in_game/common/script_values/anp_ship_values.txt')

# Presence for ship types from other mods, which the lookup can't know about.
DEFAULT_PRESENCE = 'ship_small_maritime'


def strip_comments(text):
    return re.sub(r'#[^\n]*', '', text)


def top_level_blocks(text):
    """Yield (key, body) for every top-level `key = { ... }`."""
    i, n = 0, len(text)
    for m in re.finditer(r'(?m)^\s*([A-Za-z0-9_:]+)\s*=\s*\{', text):
        if m.start() < i:
            continue
        depth, j = 0, m.end() - 1
        while j < n:
            if text[j] == '{':
                depth += 1
            elif text[j] == '}':
                depth -= 1
                if depth == 0:
                    break
            j += 1
        yield m.group(1), text[m.end():j]
        i = j + 1


def own_field(body, key):
    """Value of `key = value` at the body's own nesting level."""
    depth = 0
    for tok in re.finditer(r'\{|\}|([A-Za-z0-9_]+)\s*=\s*("[^"]*"|[^\s{}]+)', body):
        if tok.group(0) == '{':
            depth += 1
        elif tok.group(0) == '}':
            depth -= 1
        elif depth == 0 and tok.group(1) == key:
            return tok.group(2).strip('"')
    return None


def main():
    files = sorted(glob.glob(os.path.join(GAME, 'in_game/common/unit_types/*.txt')))
    files += sorted(glob.glob(os.path.join(GAME, 'dlc/*/in_game/common/unit_types/*.txt')))
    types = {}
    for path in files:
        if os.path.basename(path) == 'readme.txt':
            continue
        text = strip_comments(open(path, encoding='utf-8-sig', errors='replace').read())
        for key, body in top_level_blocks(text):
            types[key] = {f: own_field(body, f) for f in ('category', 'copy_from', 'maritime_presence')}

    def resolve(key, field, seen=()):
        t = types.get(key)
        if t is None or key in seen:
            return None
        if t[field] is not None:
            return t[field]
        return resolve(t['copy_from'], field, seen + (key,)) if t['copy_from'] else None

    def presence_terms(key, seen=()):
        """maritime_presence of `key` as a tuple of terms to add (own value plus inherited ones)."""
        t = types.get(key)
        if t is None or key in seen:
            return ()
        inherited = presence_terms(t['copy_from'], seen + (key,)) if t['copy_from'] else ()
        own = (t['maritime_presence'],) if t['maritime_presence'] is not None else ()
        return inherited + own

    navy = sorted(k for k in types if (resolve(k, 'category') or '').startswith('navy_'))
    groups = defaultdict(list)
    for k in navy:
        groups[presence_terms(k) or ('0',)].append(k)
    lines = [
        '# GENERATED by scripts/anp-build-values.py from vanilla unit_types - do not hand-edit.',
        "# Sub-unit scope: vanilla maritime_presence of this ship's type.",
        'anp_ship_maritime_presence = {',
        '\tvalue = 0',
    ]
    for i, (mp, keys) in enumerate(sorted(groups.items(), key=lambda g: (-len(g[1]), g[0]))):
        lines.append(f'\t{"if" if i == 0 else "else_if"} = {{')
        lines.append('\t\tlimit = {')
        lines.append('\t\t\tOR = {')
        lines += [f'\t\t\t\tsub_unit_type = unit_type:{k}' for k in keys]
        lines.append('\t\t\t}')
        lines.append('\t\t}')
        lines += [f'\t\tadd = {term}' for term in mp]
        lines.append('\t}')
    lines.append('\t# Ship type from another mod')
    lines.append('\telse = {')
    lines.append(f'\t\tadd = {DEFAULT_PRESENCE}')
    lines.append('\t}')
    lines.append('}')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8-sig', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    with_mp = sum(1 for k in navy if presence_terms(k))
    print(f'Wrote {OUT}: {with_mp} of {len(navy)} navy unit types have a maritime presence')
    for k in navy:
        if not presence_terms(k):
            print(f'  no maritime_presence: {k}')

if __name__ == '__main__':
    main()
